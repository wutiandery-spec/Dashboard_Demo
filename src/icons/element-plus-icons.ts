/** 注册按需图标，维持 `<component :is="'goods'">` 这类动态渲染能力 */
export function registerElementPlusIcons(app: App): void {
  Object.entries(elementPlusIcons).forEach(([name, icon]) => {
    app.component(name, icon)
  })
}
